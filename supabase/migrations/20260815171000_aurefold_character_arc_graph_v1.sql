create table if not exists public.character_arc_tracks (
  id uuid primary key default gen_random_uuid(),
  book_code text not null references public.lore_books(code) on delete cascade,
  character_id uuid not null references public.lore_entities(id) on delete cascade,
  status text not null default 'active' check (status in ('active','superseded')),
  created_by uuid null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(book_code, character_id)
);

create table if not exists public.character_arc_assessments (
  id uuid primary key default gen_random_uuid(),
  track_id uuid not null references public.character_arc_tracks(id) on delete cascade,
  source_revision_label text not null,
  manuscript_version_id uuid null references public.manuscript_versions(id) on delete set null,
  source_sha256 text null,
  assessment_status text not null default 'draft' check (assessment_status in ('draft','reviewed','superseded')),
  arc_question text null,
  starting_belief text null,
  starting_desire text null,
  starting_fear text null,
  defense_strategy text null,
  latent_need text null,
  ending_belief text null,
  ending_desire text null,
  ending_fear text null,
  changed_strategy text null,
  primary_relationships text null,
  arc_summary text null,
  notes text null,
  assessed_by uuid null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(track_id, source_revision_label)
);

create table if not exists public.character_arc_beats (
  id uuid primary key default gen_random_uuid(),
  assessment_id uuid not null references public.character_arc_assessments(id) on delete cascade,
  scene_id uuid not null references public.lore_scenes(id) on delete cascade,
  manuscript_section_id uuid null references public.manuscript_sections(id) on delete set null,
  source_body_sha256 text null,
  beat_type text not null check (beat_type in ('setup','pressure','choice','consequence','relationship_shift','revelation','setback','commitment','turning_point','payoff','other')),
  significance text not null default 'medium' check (significance in ('low','medium','high','turning_point')),
  agency_mode text not null default 'reactive' check (agency_mode in ('none','reactive','active','decisive')),
  state_before text null,
  pressure text null,
  choice_action text null,
  cost_text text null,
  state_after text null,
  belief_effect text null,
  relationship_effect text null,
  notes text null,
  created_by uuid null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(assessment_id, scene_id)
);

